"""Generate a compact, checked-in quotation table from the locked ICU data.

Build xl_quote_data explicitly, then pass its executable via --program. This
tool is not part of runtime initialization and never modifies upstream sources.
"""
import argparse
import hashlib
import json
from pathlib import Path
import subprocess

ROOT = Path(__file__).resolve().parents[1]


def generate(program, data, output):
    lock = json.loads((ROOT / 'third_party/dependencies.lock.json').read_text(encoding='utf-8'))
    deps = lock.get('dependencies', lock)
    spec = deps['icu']
    source = json.loads((ROOT / 'third_party/data/icu-quotes-source.json').read_text(encoding='utf-8'))
    data_hash = hashlib.sha256(data.read_bytes()).hexdigest()
    if spec['commit'] != source['icu_commit'] or data_hash != source['sha256']:
        raise ValueError('quotation input does not match the locked ICU source data')
    raw = subprocess.run([str(program), str(data)], check=True, stdout=subprocess.PIPE).stdout.decode('ascii')
    values = {}
    for line in raw.splitlines():
        name, *pairs = line.split('\t')
        if len(pairs) != 4 or name in values:
            raise ValueError('invalid or duplicate locale: ' + name)
        values[name.lower().replace('_', '-')] = tuple(bytes.fromhex(x) for x in pairs)
    if 'root' not in values or len(values) < 100:
        raise ValueError('incomplete ICU locale data')
    # Retain only overrides of the nearest existing parent, with root as fallback.
    selected = {}
    for name in sorted(values, key=lambda x: (x.count('-'), x)):
        parent = name.rsplit('-', 1)[0] if '-' in name else 'root'
        while parent not in values and '-' in parent:
            parent = parent.rsplit('-', 1)[0]
        if name == 'root' or values[name] != values.get(parent, values['root']):
            selected[name] = values[name]
    def literal(value):
        return '"' + ''.join('\\x{:02x}'.format(x) for x in value) + '"'
    lines = ['// Generated by tools/generate_quotes.py from ICU/CLDR; Unicode-3.0.',
             '// ICU commit: ' + spec['commit'],
             '// Input source/data/in/icudt79l.dat SHA256: ' + data_hash,
             '// Original license: third_party/dependencies.lock.json -> ICU LICENSE (included in SDK).',
             '// {} resolved locales, {} distinct parent overrides.'.format(len(values), len(selected))]
    for name in sorted(selected):
        lines.append('    {"' + name + '", {' + ', '.join(literal(x) for x in selected[name]) + '}},')
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text('\n'.join(lines) + '\n', encoding='utf-8')
    print('{} locales -> {} overrides, {} bytes'.format(len(values), len(selected), output.stat().st_size))


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--program', required=True, type=Path)
    parser.add_argument('--data', required=True, type=Path)
    parser.add_argument('--output', type=Path, default=ROOT / 'third_party/data/icu-quotes.inc')
    args = parser.parse_args()
    generate(args.program.resolve(), args.data.resolve(), args.output.resolve())
